interface TablePhase {
    type: "table";
    rates: readonly number[];
    start: number;
    end: number;
    baseRaw: number;
    initialBlockSize: number;
    blockSize: number;
}

interface FormulaPhase {
    type: "formula";
    start: number;
    end: number;
    baseRaw: number;
    getIncrement: (level: number) => number;
}

type Phase = TablePhase | FormulaPhase;

export const MIN_STAT_VALUE = 0;
export const MAX_STAT_VALUE = 2500;

// NOTE: The following code block was adapated from daftuyda.moe's rating calculator
/**
    Stat score lookup table, pre-computed from the umakonga formula.
    Three scoring ranges with different block granularities:

        `0-1200`: 50-pt blocks (25 rates)
        `1201-2000`: 10-pt blocks (81 rates, base 38413 at stat 1200)
        `2001-2500`: 25-pt blocks (rate 183+, base 142796 at stat 2000)

    Raw per-point values are accumulated then: `Math.round(raw / 10)`.
*/
export const statScores = (() => {
    const R1 = [
        5, 8, 10, 13, 16, 18, 21, 24, 26, 28, 29, 30, 31, 33, 34, 35, 39, 41,
        42, 43, 52, 55, 66, 68, 68,
    ] as const;
    const R2 = [
        79, 80, 81, 83, 84, 85, 86, 88, 89, 90, 92, 93, 94, 96, 97, 98, 100,
        101, 102, 103, 105, 106, 107, 109, 110, 111, 113, 114, 115, 117, 118,
        119, 121, 122, 123, 124, 126, 127, 128, 130, 131, 132, 134, 135, 136,
        138, 139, 140, 141, 143, 144, 145, 147, 148, 149, 151, 152, 153, 155,
        156, 157, 159, 160, 161, 162, 164, 165, 166, 168, 169, 170, 172, 173,
        174, 176, 177, 178, 179, 181, 182, 182,
    ] as const;

    const phases: readonly Phase[] = [
        {
            type: "table",
            rates: R1,
            start: 1,
            end: 1200,
            baseRaw: 0,
            // Level 1-49 uses R1[0]
            initialBlockSize: 49,
            // Then every 50 levels
            blockSize: 50,
        },
        {
            type: "table",
            rates: R2,
            start: 1201,
            end: 2000,
            baseRaw: 38413,
            // Level 1201-1209 uses R2[0]
            initialBlockSize: 9,
            // Then every 10 levels
            blockSize: 10,
        },
        {
            type: "formula",
            start: 2001,
            end: MAX_STAT_VALUE,
            baseRaw: 142796,
            getIncrement(level) {
                // 183 for levels 2001-2025,
                // 184 for levels 2026-2050, etc.
                return 183 + Math.floor((level - 2001) / 25);
            },
        },
    ];

    const scores = new Array<number>(MAX_STAT_VALUE + 1).fill(0);
    for (const phase of phases) {
        let raw = phase.baseRaw;
        for (let level = phase.start; level <= phase.end; level++) {
            let increment: number;
            if (phase.type === "table") {
                let rateIndex: number;
                if (level < phase.start + phase.initialBlockSize) {
                    rateIndex = 0;
                } else {
                    rateIndex =
                        1 +
                        Math.floor(
                            (level - phase.start - phase.initialBlockSize) /
                                phase.blockSize,
                        );
                }
                rateIndex = Math.min(rateIndex, phase.rates.length - 1);
                increment = phase.rates[rateIndex];
            } else {
                increment = phase.getIncrement(level);
            }
            raw += increment;
            scores[level] = Math.round(raw / 10);
        }
    }
    return scores;
})();

export const statRanks = (() => {
    const ranks = new Array<number>(MAX_STAT_VALUE + 1);

    for (let value = 0; value <= MAX_STAT_VALUE; value++) {
        if (value < 400) {
            ranks[value] = Math.floor(value / 50);
        } else if (value < 1000) {
            ranks[value] = 8 + Math.floor((value - 400) / 100);
        } else if (value < 1150) {
            ranks[value] = 14 + Math.floor((value - 1000) / 50);
        } else if (value <= 1200) {
            ranks[value] = 17;
        } else if (value < 2000) {
            ranks[value] = 18 + Math.floor((value - 1200) / 10);
        } else {
            ranks[value] = 98 + Math.max(0, Math.floor((value - 2001) / 5));
        }
    }

    return ranks;
})();

