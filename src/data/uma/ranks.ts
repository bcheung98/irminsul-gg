export const badgeSpriteMap: Record<string, SpriteMap> = (() => {
    const map = {
        ...rankSpriteMap,
    };
    for (const [family, cells] of Object.entries(highRankSpriteGrid)) {
        cells.forEach(([row, col], idx) => {
            const label = idx === 0 ? family : `${family}${idx}`;
            map[label as keyof typeof map] = {
                x: highRankSpriteCellX + col * highRankSpriteCellStep,
                y: highRankSpriteCellY + (row - 1) * highRankSpriteCellStep,
                w: highRankSpriteWidth,
                h: highRankSpriteHeight,
            };
        });
    }
    return map;
})();

